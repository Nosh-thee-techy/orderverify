const VERDICT_COLOR: Record<string, { text: string; bg: string }> = {
  RELEASE: { text: "#0E9F5B", bg: "#E3F8EC" },
  REVIEW: { text: "#2457D6", bg: "#E3EBFF" },
  HOLD: { text: "#B3122B", bg: "#FBE0E4" },
};

/**
 * Render the stored report as an HTML email.
 *
 * @param report - Engine report already persisted for this seller
 * @param orders - Order names and claimed payment codes
 * @param lang - Seller language
 * @returns HTML email body
 */
export function renderReportEmail(
  report: BatchReport,
  orders: ReportOrderSource[],
  lang: "en" | "sw",
): string {
  const doc = buildReportDocument(report, orders, lang);
  const t = copy[lang];
  const grouped = groupReportOrders(doc.orders);
  const evidence = doc.tier === "STATEMENT_VERIFIED" ? t.statement : t.textOnly;
  const rows = doc.orders
    .map((order) => {
      const color = VERDICT_COLOR[order.verdict] ?? { text: "#2457D6", bg: "#E3EBFF" };
      return `<tr>
        <td style="padding:10px 8px;border-bottom:1px solid #F0E2C8">${escapeHtml(order.customerName)}<br/><span style="color:#7A6670;font-size:12px">${escapeHtml(order.orderRef)}</span></td>
        <td style="padding:10px 8px;border-bottom:1px solid #F0E2C8">${escapeHtml(order.paymentRef ?? "—")}</td>
        <td style="padding:10px 8px;border-bottom:1px solid #F0E2C8">${money(order.expectedAmountKes)}</td>
        <td style="padding:10px 8px;border-bottom:1px solid #F0E2C8">${money(order.receivedAmountKes)}</td>
        <td style="padding:10px 8px;border-bottom:1px solid #F0E2C8"><span style="display:inline-block;padding:4px 8px;border-radius:999px;background:${color.bg};color:${color.text};font-size:12px;font-weight:600">${order.verdict}</span></td>
        <td style="padding:10px 8px;border-bottom:1px solid #F0E2C8">${escapeHtml(order.explanation)}</td>
      </tr>`;
    })
    .join("");
  const findings = (["RELEASE", "REVIEW", "HOLD"] as const)
    .map((verdict) => {
      const items = grouped[verdict];
      if (items.length === 0) return "";
      const label = verdict === "RELEASE" ? t.release : verdict === "REVIEW" ? t.review : t.hold;
      const lis = items.map((item) => `<li style="margin:0 0 8px">${escapeHtml(item.customerName)} — ${escapeHtml(item.explanation)}</li>`).join("");
      return `<h3 style="margin:24px 0 8px;font-size:16px">${escapeHtml(label)}</h3><ul style="padding-left:18px;margin:0">${lis}</ul>`;
    })
    .join("");
  const unmatched =
    doc.unmatchedPayments.length === 0
      ? ""
      : `<h3 style="margin:24px 0 8px;font-size:16px">${escapeHtml(t.unmatched)}</h3>
         <p>${doc.unmatchedPayments.map((item) => escapeHtml(item.code ?? item.paymentId)).join(", ")}</p>`;

  return `<div style="font-family:DM Sans,system-ui,sans-serif;color:#2A1020;background:#FFFBF0;padding:24px">
    <div style="max-width:720px;margin:0 auto;background:#FFFFFF;border:1px solid #F0E2C8;border-radius:16px;padding:28px">
      <p style="margin:0 0 4px;font-size:12px;letter-spacing:0.16em;text-transform:uppercase;color:#E4701D">OrderVerify</p>
      <h1 style="margin:0 0 8px;font-size:22px">${escapeHtml(t.title)}</h1>
      <p style="margin:0 0 16px;color:#7A6670;font-size:14px">${escapeHtml(t.batch)} ${escapeHtml(doc.batchRef)} · ${escapeHtml(t.complete)} · ${escapeHtml(evidence)}</p>
      <h2 style="margin:0 0 8px;font-size:18px">${escapeHtml(t.introTitle)}</h2>
      <p style="margin:0 0 20px;line-height:1.6">${escapeHtml(t.introBody)}</p>
      <table style="width:100%;border-collapse:collapse;margin-bottom:20px">
        <tr>
          ${summaryCell(t.total, String(doc.counts.total), "#2A1020", "#FFF8E4")}
          ${summaryCell(t.release, String(doc.counts.release), "#0E9F5B", "#E3F8EC")}
          ${summaryCell(t.review, String(doc.counts.review), "#2457D6", "#E3EBFF")}
          ${summaryCell(t.hold, String(doc.counts.hold), "#B3122B", "#FBE0E4")}
        </tr>
      </table>
      <table style="width:100%;border-collapse:collapse;text-align:left;font-size:13px">
        <thead>
          <tr style="background:#FFF8E4">
            <th style="padding:8px">${escapeHtml(t.order)}</th>
            <th style="padding:8px">${escapeHtml(t.payment)}</th>
            <th style="padding:8px">${escapeHtml(t.expected)}</th>
            <th style="padding:8px">${escapeHtml(t.received)}</th>
            <th style="padding:8px">Status</th>
            <th style="padding:8px">${escapeHtml(t.explanation)}</th>
          </tr>
        </thead>
        <tbody>${rows}</tbody>
      </table>
      ${findings}
      ${unmatched}
      <p style="margin:28px 0 0;color:#7A6670;font-size:13px;line-height:1.6">${escapeHtml(t.disclaimer)}</p>
      <p style="margin:8px 0 0;font-size:13px">${escapeHtml(t.generatedBy)} · ${escapeHtml(t.title)}</p>
    </div>
  </div>`;
}

function summaryCell(label: string, value: string, color: string, bg: string): string {
  return `<td style="padding:8px"><div style="background:${bg};border-radius:12px;padding:12px;text-align:center"><div style="font-size:20px;font-weight:700;color:${color}">${escapeHtml(value)}</div><div style="font-size:12px;color:${color}">${escapeHtml(label)}</div></div></td>`;
}

function money(amount: number | null): string {
  return amount == null ? "—" : escapeHtml(formatKes(amount));
}

function escapeHtml(value: string): string {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}
