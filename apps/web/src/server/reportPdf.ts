/**
 * Build a multi-page PDF for a stored batch report.
 *
 * @param report - Engine report
 * @param orders - Names and claimed codes
 * @param lang - en or sw
 * @returns PDF bytes
 */
export async function buildReportPdf(
  report: BatchReport,
  orders: ReportOrderSource[],
  lang: "en" | "sw",
): Promise<Uint8Array> {
  const doc = buildReportDocument(report, orders, lang);
  const t = copy[lang];
  const pdf = await PDFDocument.create();
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const pages: PDFPage[] = [];
  let page = pdf.addPage([595.28, 841.89]);
  pages.push(page);
  const margin = 48;
  const width = page.getWidth() - margin * 2;
  let y = page.getHeight() - margin;

  const ensure = (need: number) => {
    if (y - need > margin + 36) return;
    page = pdf.addPage([595.28, 841.89]);
    pages.push(page);
    y = page.getHeight() - margin;
    drawTableHeader(page, bold, margin, y, width, t);
    y -= 22;
  };

  page.drawRectangle({ x: 0, y: page.getHeight() - 10, width: page.getWidth(), height: 10, color: YELLOW });
  page.drawRectangle({ x: 0, y: page.getHeight() - 14, width: page.getWidth() / 2, height: 4, color: ORANGE });
  page.drawRectangle({ x: page.getWidth() / 2, y: page.getHeight() - 14, width: page.getWidth() / 2, height: 4, color: PINK });

  y -= 8;
  draw(page, "OrderVerify", bold, 11, margin, y, ORANGE);
  y -= 22;
  draw(page, t.title, bold, 18, margin, y, PLUM);
  y -= 16;
  const when = new Date(doc.createdAt).toISOString().replace("T", " ").slice(0, 16) + " UTC";
  const evidence = doc.tier === "STATEMENT_VERIFIED" ? t.statement : t.textOnly;
  draw(page, `${t.batch} ${doc.batchRef}  ·  ${t.complete}  ·  ${when}`, regular, 10, margin, y, MUTED);
  y -= 14;
  draw(page, evidence, regular, 10, margin, y, MUTED);
  y -= 22;
  draw(page, t.introTitle, bold, 13, margin, y, PLUM);
  y -= 16;
  y = wrap(page, t.introBody, regular, 11, margin, y, width, PLUM);

  y -= 10;
  const cards = [
    { label: t.total, value: String(doc.counts.total), color: PLUM },
    { label: t.release, value: String(doc.counts.release), color: BRAND_ORANGE },
    { label: t.review, value: String(doc.counts.review), color: BLUE },
    { label: t.hold, value: String(doc.counts.hold), color: HOLD },
  ];
  const cardW = (width - 18) / 4;
  cards.forEach((card, index) => {
    const x = margin + index * (cardW + 6);
    page.drawRectangle({ x, y: y - 36, width: cardW, height: 44, color: CREAM, borderColor: LINE, borderWidth: 1 });
    draw(page, card.value, bold, 14, x + 8, y - 14, card.color);
    draw(page, card.label, regular, 8, x + 8, y - 28, card.color);
  });
  y -= 56;

  drawTableHeader(page, bold, margin, y, width, t);
  y -= 22;

  for (const order of doc.orders) {
    const explanation = wrapPreview(order.explanation, regular, 8, 150);
    const rowH = Math.max(28, 12 + explanation.length * 10);
    ensure(rowH + 4);
    const cells = [
      `${order.customerName}\n${order.orderRef}`,
      order.paymentRef ?? "—",
      money(order.expectedAmountKes),
      money(order.receivedAmountKes),
      order.verdict,
      order.explanation,
    ];
    const widths = colWidths(width);
    let x = margin;
    cells.forEach((cell, index) => {
      const col = widths[index] ?? width / 6;
      const lines = wrapPreview(cell, regular, 8, col - 6);
      lines.forEach((line, lineIndex) => {
        draw(page, line, regular, 8, x + 3, y - 10 - lineIndex * 10, index === 4 ? verdictColor(order.verdict) : PLUM);
      });
      x += col;
    });
    page.drawLine({ start: { x: margin, y: y - rowH + 6 }, end: { x: margin + width, y: y - rowH + 6 }, thickness: 0.5, color: LINE });
    y -= rowH;
  }

  const grouped = groupReportOrders(doc.orders);
  y -= 12;
  ensure(24);
  draw(page, t.findings, bold, 13, margin, y, PLUM);
  y -= 18;
  for (const verdict of ["RELEASE", "REVIEW", "HOLD"] as const) {
    const items = grouped[verdict];
    if (items.length === 0) continue;
    const label = verdict === "RELEASE" ? t.release : verdict === "REVIEW" ? t.review : t.hold;
    ensure(20);
    draw(page, label, bold, 11, margin, y, verdictColor(verdict));
    y -= 14;
    for (const item of items) {
      ensure(24);
      y = wrap(page, `• ${item.customerName} — ${item.explanation}`, regular, 10, margin, y, width, PLUM);
      y -= 4;
    }
  }

  if (doc.unmatchedPayments.length > 0) {
    ensure(28);
    draw(page, t.unmatched, bold, 11, margin, y, PLUM);
    y -= 14;
    y = wrap(
      page,
      doc.unmatchedPayments.map((item) => item.code ?? item.paymentId).join(", "),
      regular,
      10,
      margin,
      y,
      width,
      MUTED,
    );
  }

  y -= 16;
  ensure(48);
  y = wrap(page, t.disclaimer, regular, 9, margin, y, width, MUTED);
  y -= 12;
  draw(page, `${t.generatedBy}  ·  ${t.title}`, regular, 9, margin, y, MUTED);

  const total = pages.length;
  pages.forEach((item, index) => {
    item.drawText(`${t.page} ${index + 1} / ${total}`, {
      x: item.getWidth() - margin - 70,
      y: 24,
      size: 9,
      font: regular,
      color: MUTED,
    });
  });

  return pdf.save();
}

function drawTableHeader(page: PDFPage, font: PDFFont, margin: number, y: number, width: number, t: Labels) {
  page.drawRectangle({ x: margin, y: y - 16, width, height: 18, color: CREAM });
  const labels = [t.order, t.payment, t.expected, t.received, t.verdict, t.explanation];
  const widths = colWidths(width);
  let x = margin;
  labels.forEach((label, index) => {
    draw(page, label, font, 8, x + 3, y - 12, ORANGE);
    x += widths[index] ?? width / 6;
  });
}

function colWidths(width: number): number[] {
  return [width * 0.18, width * 0.14, width * 0.12, width * 0.12, width * 0.12, width * 0.32];
}

function draw(page: PDFPage, text: string, font: PDFFont, size: number, x: number, y: number, color: ReturnType<typeof rgb>) {
  page.drawText(sanitize(text), { x, y, size, font, color });
}

function wrap(
  page: PDFPage,
  text: string,
  font: PDFFont,
  size: number,
  x: number,
  y: number,
  width: number,
  color: ReturnType<typeof rgb>,
): number {
  const lines = wrapPreview(text, font, size, width);
  lines.forEach((line, index) => {
    page.drawText(line, { x, y: y - index * (size + 3), size, font, color });
  });
  return y - lines.length * (size + 3);
}

function wrapPreview(text: string, font: PDFFont, size: number, width: number): string[] {
  const words = sanitize(text).split(/\s+/);
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (font.widthOfTextAtSize(next, size) > width && current) {
      lines.push(current);
      current = word;
    } else {
      current = next;
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : [""];
}

function verdictColor(verdict: string) {
  if (verdict === "RELEASE") return BRAND_ORANGE;
  if (verdict === "HOLD") return HOLD;
  return BLUE;
}

function money(amount: number | null): string {
  return amount == null ? "—" : formatKes(amount);
}

function sanitize(value: string): string {
  return value.replace(/[\u0000-\u001f]/g, " ").replace(/[^\x20-\x7E]/g, (char) => {
    // Helvetica cannot encode most non-Latin glyphs; keep readable ASCII fallbacks.
    if (char === "—" || char === "–") return "-";
    if (char === "’" || char === "‘") return "'";
    return char.charCodeAt(0) > 127 ? "?" : char;
  });
}
